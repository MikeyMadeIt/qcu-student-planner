-- Cached metadata for public QCU publications. Mutations are restricted to the
-- sync Edge Function (service role); approved planner users have read access.
create table if not exists public.qcu_news_articles (
    id bigint generated by default as identity primary key,
    external_id bigint,
    article_url text not null unique,
    title text not null,
    excerpt text,
    featured_image_url text,
    published_at timestamptz not null,
    modified_at timestamptz,
    category text not null check (category in ('news', 'announcement')),
    source_name text not null default 'Quezon City University',
    synced_at timestamptz not null default now(),
    constraint qcu_news_articles_external_id_key unique (external_id)
);
create index if not exists qcu_news_articles_published_idx on public.qcu_news_articles (published_at desc, id desc);
alter table public.qcu_news_articles enable row level security;
drop policy if exists qcu_news_articles_read_approved on public.qcu_news_articles;
create policy qcu_news_articles_read_approved on public.qcu_news_articles
    for select to authenticated using ((select public.is_approved()));
revoke insert, update, delete, truncate, references, trigger on public.qcu_news_articles from anon, authenticated;
grant select on public.qcu_news_articles to authenticated;

create table if not exists public.qcu_news_sync_state (
    id boolean primary key default true check (id),
    last_success_at timestamptz,
    last_attempt_at timestamptz,
    last_error text,
    lock_until timestamptz
);
insert into public.qcu_news_sync_state (id) values (true) on conflict (id) do nothing;
alter table public.qcu_news_sync_state enable row level security;
revoke all on public.qcu_news_sync_state from anon, authenticated;
grant all on public.qcu_news_sync_state to service_role;
grant select on public.qcu_news_articles to service_role;
grant insert, update on public.qcu_news_articles to service_role;
grant usage, select on all sequences in schema public to service_role;

-- A single atomic claim prevents simultaneous manual/cron refreshes.
create or replace function public.claim_qcu_news_sync(p_now timestamptz, p_lock_until timestamptz)
returns boolean language plpgsql security definer set search_path = public
as $$
declare claimed boolean;
begin
    update public.qcu_news_sync_state
       set last_attempt_at = p_now, lock_until = p_lock_until
     where id = true and (lock_until is null or lock_until <= p_now)
     returning true into claimed;
    return coalesce(claimed, false);
end;
$$;
revoke all on function public.claim_qcu_news_sync(timestamptz, timestamptz) from public, anon, authenticated;
grant execute on function public.claim_qcu_news_sync(timestamptz, timestamptz) to service_role;
